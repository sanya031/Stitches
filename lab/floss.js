export const FLOSS = DMC.map(([dmc, name, hex, anchor]) => ({ dmc, name, hex, anchor }));

// ---------- a darker thread of about the same colour ----------

function lab(hex) {
  const v = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4)));
  const f = (t) => (t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116);
  const x = f((v[0] * 0.4124 + v[1] * 0.3576 + v[2] * 0.1805) / 0.95047), y = f(v[0] * 0.2126 + v[1] * 0.7152 + v[2] * 0.0722), z = f((v[0] * 0.0193 + v[1] * 0.1192 + v[2] * 0.9505) / 1.08883);
  return [116 * y - 16, 500 * (x - y), 200 * (y - z)];
}
let LAB = null;

const family = (f) => f.name.split(' · ')[0];

/** A darker thread of about the same colour (outlines look stitched with the neighbouring colour, not black): a darker
 * shade of the same DMC family, about `steps` × 9 lightness darker, when the family has one; else the darker thread
 * whose colour (a, b) is closest; black stays black. */
export function darkerShade(index, steps = 2) {
  LAB ||= FLOSS.map((f) => lab(f.hex));
  const [L, a, b] = LAB[index], want = L - steps * 9, fam = family(FLOSS[index]);
  if (L < 12) return index;
  const pick = (ok) => {
    let best = -1, bd = Infinity;
    LAB.forEach(([l2, a2, b2], j) => {
      if (l2 >= L - 4 || !ok(j)) return;
      const d = (a2 - a) ** 2 + (b2 - b) ** 2 + 0.6 * (l2 - want) ** 2;
      if (d < bd) { bd = d; best = j; }
    });
    return best;
  };
  const same = pick((j) => family(FLOSS[j]) === fam);
  return same >= 0 ? same : Math.max(index, pick(() => true));
}

/** The nearest thread to any colour (index into FLOSS), by distance in Lab. */
export function nearestFloss(hex) {
  LAB ||= FLOSS.map((f) => lab(f.hex));
  const [L, a, b] = lab(hex);
  let best = 0, bd = Infinity;
  LAB.forEach(([l2, a2, b2], j) => { const d = (l2 - L) ** 2 + (a2 - a) ** 2 + (b2 - b) ** 2; if (d < bd) { bd = d; best = j; } });
  return best;
}

/** An outline's thread for a colour, as the picture draws it: a darker shade of the same DMC family. Cached. */
const SHADES = new Map();
export function outlineShade(hex) {
  const k = hex.toUpperCase();
  if (!SHADES.has(k)) SHADES.set(k, FLOSS[darkerShade(nearestFloss(k))].hex);
  return SHADES.get(k);
}

/** A colour's lightness (Lab L, 0–100). */
export const lightness = (hex) => lab(hex)[0];
